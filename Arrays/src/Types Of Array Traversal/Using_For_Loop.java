public class Using_For_Loop {
    public static void main(String[]args){              //Range Based For Loop

                int[] arr = {1,2,3,4,5};                //TC O(n)       SC O(1)
                   
                System.out.print("Traversal Using For Loop : ");

                for(int value:arr){
                            System.out.print(value + " ");
                }

                System.out.println();

    }
    
}
