public class Using_While_Loop {
    public static void main (String[]args){

            int[] arr = {100,200,300,400,500};

                int n = arr.length;                 //TC O(n)       SC O(1)
                int i = 0;
                            System.out.print("Using_While_Loop : ");
                        while(i<n){
                            System.out.print(arr[i] + " ");
                            i++;
                        }
                             System.out.println();
                       
                    }
    }
    

